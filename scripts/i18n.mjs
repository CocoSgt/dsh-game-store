#!/usr/bin/env node
/**
 * The store's languages beyond Chinese and English.
 *
 *   node scripts/i18n.mjs
 *
 * i18n/<lang>.json holds the store page's texts (the same keys as the en dictionary in lib/client.js); this script
 * writes them into the generated block of lib/client.js, so the plugin stays one file. Missing keys fall back to
 * English at run time, and the script lists them. The website's texts live in site/i18n/<lang>.mjs.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const clientFile = join(root, 'lib/client.js')
let client = readFileSync(clientFile, 'utf8')

const enSrc = /const en = \{\n([\s\S]*?)\n\};\n/.exec(client)[1]
const en = (0, eval)(`({${enSrc}})`)
const langs = readdirSync(join(root, 'i18n')).filter(f => /^[a-z]{2}\.json$/.test(f)).map(f => f.slice(0, 2)).sort()
const more = {}
for (const lang of langs) {
  const dict = JSON.parse(readFileSync(join(root, 'i18n', `${lang}.json`), 'utf8'))
  const missing = Object.keys(en).filter(k => typeof dict[k] !== 'string')
  const extra = Object.keys(dict).filter(k => !(k in en))
  for (const k of extra) delete dict[k]
  // A placeholder dropped in translation would show raw text; English is used for that key instead.
  for (const k of Object.keys(dict)) {
    const want = (en[k].match(/\{[a-zA-Z]+\}/g) ?? []).sort().join()
    if ((dict[k].match(/\{[a-zA-Z]+\}/g) ?? []).sort().join() !== want) { console.warn(`${lang}: ${k} has other placeholders than English; English is used`); delete dict[k] }
  }
  if (missing.length) console.warn(`${lang}: ${missing.length} missing (${missing.slice(0, 6).join(', ')}${missing.length > 6 ? ', …' : ''}); English is used for them`)
  more[lang] = dict
}
const block = `/* i18n:begin — generated by scripts/i18n.mjs from i18n/*.json; edit those, not this block */\nconst more = ${JSON.stringify(more)};\n/* i18n:end */`
client = client.replace(/\/\* i18n:begin[\s\S]*?\/\* i18n:end \*\//, block)
writeFileSync(clientFile, client)
console.log(`lib/client.js: ${langs.join(', ')} (${Object.keys(en).length} texts each)`)
